import { useEffect, useState } from 'react';
import { preparedSummary, type SummaryResponse } from '../domain/summary';
import type { RetrievalResult } from '../domain/types';

const CLIENT_TIMEOUT_MS = 9500;
type Shown = Exclude<SummaryResponse, { source: 'none' }>;

/** One request per machine per page load. The flow never waits for it. */
const requests = new Map<string, Promise<Shown>>();

export function resetSummaryRequests() {
  requests.clear();
}

async function requestSummary(result: RetrievalResult): Promise<Shown> {
  const fallback: Shown = { source: 'prepared', sentences: preparedSummary(result) };
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), CLIENT_TIMEOUT_MS);
  try {
    const response = await fetch('/api/summary', {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ assetId: result.asset.id }),
      signal: controller.signal,
    });
    if (!response.ok) return fallback;
    const body = (await response.json()) as SummaryResponse;
    return body.source === 'none' || !Array.isArray(body.sentences) ? fallback : body;
  } catch {
    return fallback;
  } finally {
    clearTimeout(timer);
  }
}

function summaryFor(result: RetrievalResult): Promise<Shown> {
  let request = requests.get(result.asset.id);
  if (!request) {
    request = requestSummary(result);
    requests.set(result.asset.id, request);
  }
  return request;
}

export function SummaryCard({ result, sourceHref }: { result: RetrievalResult; sourceHref: (id: string) => string }) {
  const [summary, setSummary] = useState<Shown | null>(null);

  useEffect(() => {
    let current = true;
    void summaryFor(result).then((value) => {
      if (current) setSummary(value);
    });
    return () => {
      current = false;
    };
  }, [result]);

  if (!summary) {
    return (
      <section className="summary" aria-label="Evidence summary" aria-busy="true">
        <p className="summary-loading">Loading summary</p>
      </section>
    );
  }

  return (
    <section className="summary" aria-label="Evidence summary" data-source={summary.source}>
      <ul className="summary-list">
        {summary.sentences.map((sentence) => (
          <li key={sentence.text}>
            {sentence.text}
            {sentence.citations.map((id) => (
              <a key={id} className="cite" href={sourceHref(id)} aria-label={`Source ${id}`}>{id}</a>
            ))}
          </li>
        ))}
      </ul>
      <p className="summary-label">
        {summary.source === 'gemini' ? 'Generated by Gemini from the records below' : 'Prepared summary, AI unavailable'}
      </p>
    </section>
  );
}
